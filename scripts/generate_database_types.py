#!/usr/bin/env python3
"""Generate the Supabase public contract from the migrated disposable database.
Run test_database.py first. --check detects drift without changing the file.
"""
import json
import pathlib
import subprocess
import sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'supabase/tests'))
from db_support import DB

def query(sql):
    return json.loads(subprocess.check_output(['psql', DB, '-XAt', '-v', 'ON_ERROR_STOP=1', '-c', sql], text=True))

tables = query("""SELECT json_agg(t ORDER BY name) FROM (
 SELECT c.relname name, (SELECT json_agg(json_build_object('name',a.attname,'type',format_type(a.atttypid,NULL),'nullable',NOT a.attnotnull,'optional',a.atthasdef OR NOT a.attnotnull) ORDER BY a.attnum)
 FROM pg_attribute a WHERE a.attrelid=c.oid AND a.attnum>0 AND NOT a.attisdropped) columns
 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relkind='r') t""")
functions = query("""SELECT json_agg(t ORDER BY name) FROM (
 SELECT p.proname name,format_type(p.prorettype,NULL) returns,p.proretset many,
 (SELECT coalesce(json_agg(json_build_object('name',p.proargnames[a.i],'type',format_type(p.proargtypes[a.i-1],NULL),'optional',a.i>p.pronargs-p.pronargdefaults) ORDER BY a.i),'[]'::json)
 FROM generate_series(1,p.pronargs) a(i)) args
 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND p.prorettype<>'trigger'::regtype) t""")
names = {t['name'] for t in tables}
def ts_type(value):
    if value.endswith('[]'): return '(' + ts_type(value[:-2]) + ')[]'
    if value in ('json','jsonb'): return 'Json'
    if value in ('integer','bigint','smallint','numeric','real','double precision'): return 'number'
    if value == 'boolean': return 'boolean'
    if value == 'void': return 'undefined'
    if value in names: return "Database['public']['Tables'][%s]['Row']" % json.dumps(value)
    return 'string'

lines = ['// Generated by scripts/generate_database_types.py from migrations. Do not edit.',
 'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];',
 'export type Database = { public: { Tables: {']
for table in tables:
    lines.append(json.dumps(table['name']) + ': {')
    for mode in ('Row','Insert','Update'):
        lines.append(mode + ': {')
        for col in table['columns']:
            optional = mode == 'Update' or (mode == 'Insert' and col['optional'])
            value = ts_type(col['type']) + (' | null' if col['nullable'] else '')
            lines.append(json.dumps(col['name']) + ('?' if optional else '') + ': ' + value + ';')
        lines.append('};')
    lines.append('Relationships: []; };')
lines += ['}; Views: { [_ in never]: never }; Functions: {']
for fn in functions:
    args = ' '.join(json.dumps(a['name']) + ('?' if a['optional'] else '') + ': ' + ts_type(a['type']) + ' | null' + ';' for a in fn['args'])
    value = ts_type(fn['returns']) + ('[]' if fn['many'] else '')
    lines.append(json.dumps(fn['name']) + ': { Args: ' + ('{' + args + '}' if args else 'Record<string, never>') + '; Returns: ' + value + ' };')
lines += ['}; Enums: { [_ in never]: never }; CompositeTypes: { [_ in never]: never } } };', '']
# Use the repository formatter so CI comparison is stable.
source = subprocess.check_output([str(ROOT / 'node_modules/.bin/prettier'), '--parser', 'typescript'], input='\n'.join(lines), text=True)
target = ROOT / 'src/types/supabase.generated.ts'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != source:
        sys.exit('Database types differ. Run python3 scripts/generate_database_types.py after database tests.')
else:
    target.write_text(source)
